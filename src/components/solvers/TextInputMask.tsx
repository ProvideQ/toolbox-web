import { Divider } from "@chakra-ui/react";
import Head from "next/head";
import { ReactElement, useState } from "react";
import { baseUrl } from "../../api/toolbox/ToolboxAPI";
import { Container } from "../Container";
import { EditorControls } from "./EditorControls";
import {
  GrammarSettings,
  SyntaxHighlightedTextarea,
} from "./SAT/SyntaxHighlightedTextarea";

export interface TextInputMaskProperties {
  problemTypeId: string;
  textPlaceholder: string;
  text: string;
  setText: (text: string) => void;
  compact?: boolean;
  validate?: (text: string) => string[] | null;
  grammar?: GrammarSettings;
  body?: ReactElement;
}

export const TextInputMask = (props: TextInputMaskProperties) => {
  const [errorString, setErrorString] = useState("");

  function onTextChanged(newText: string): void {
    try {
      props.setText(newText);

      let errors = props.validate?.(newText);
      if (errors) {
        setErrorString(errors.toString());
      } else {
        setErrorString("");
      }
    } catch (e: any) {
      setErrorString(e.message);
    }
  }

  return (
    <Container
      gap={props.compact ? "0.75rem" : "1rem"}
      padding={props.compact ? "0" : "8px"}
      bg={props.compact ? "transparent" : "gray.50"}
      alignItems={props.compact ? "stretch" : "center"}
      _dark={{
        bg: props.compact ? "transparent" : "gray.900",
        color: "white",
      }}
    >
      <Head>
        <title>ProvideQ</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/favicon.ico" />
        {/* TODO: replace favicon */}
      </Head>

      <EditorControls
        problemTypeId={props.problemTypeId}
        errorText={errorString}
        // idleText={props.textPlaceholder + " 👇"}
        idleText=""
        setEditorContent={onTextChanged}
        editorContent={props.text}
        compact={props.compact}
        documentationLink={`${baseUrl()}/webjars/swagger-ui/index.html#/${
          props.problemTypeId
        }`}
      />

      <SyntaxHighlightedTextarea
        text={props.text}
        setText={onTextChanged}
        placeholder={props.textPlaceholder}
        isInvalid={errorString != ""}
        grammar={props.grammar}
        compact={props.compact}
      />

      {props.body}

      {!props.compact && <Divider />}
    </Container>
  );
};
